#!/usr/bin/env bash
# Bubble animation on/off for the Frutiger Aero bar.
#
# State lives in ../bubbles-anim.css, which style.css @imports:
#   on  -> the drifting animation      (~34% of a core on this laptop)
#   off -> animation: none             (bubbles stay, frozen; ~0% CPU)
#
#   bubbles.sh          print status JSON for the waybar module
#   bubbles.sh toggle   flip the state and reload waybar's style

DIR="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
STATE="$DIR/bubbles-anim.css"

# 60s loop in 1800 steps = 30 updates/s (see style.css perf note)
ON='window#waybar { animation: aero-bubbles 60s steps(1800) infinite; }'
OFF='window#waybar { animation: none; }'

is_on() { grep -q 'aero-bubbles' "$STATE" 2>/dev/null; }

write_state() {
  printf '/* generated by scripts/bubbles.sh: toggled from the bar */\n%s\n' "$1" > "$STATE"
}

case "$1" in
  toggle)
    if is_on; then write_state "$OFF"; else write_state "$ON"; fi
    pkill -USR2 -x waybar   # SIGUSR2 = reload config + style
    ;;
  *)
    [ -f "$STATE" ] || write_state "$ON"
    if is_on; then
      echo '{"text": "🫧", "class": "on", "tooltip": "Bubbles drifting: click to freeze"}'
    else
      echo '{"text": "🫧", "class": "off", "tooltip": "Bubbles frozen: click to animate"}'
    fi
    ;;
esac
